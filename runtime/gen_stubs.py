"""Generates runtime/rt_asm.s: the assembly stubs between translated code and the C runtime.
Rules: the x86 stack must stay exactly as the program left it, so stubs never use it for scratch data: registers are saved in the
context, C runs on its own stack, and the 4-byte return address pushed by `jbsr` is zeroed again (DOS4GW zero-filled stacks and the
program reads uninitialised stack words)."""
OUT = []
def w(s): OUT.append(s)
CTXREGS = 96     # struct ctx.regs[8]
w('''| generated by gen_stubs.py - do not edit
	.text
	.even
	.globl rt_enter
rt_enter:			| rt_enter(win, ctx, esp, entry)
	movem.l %d2-%d7/%a2-%a6,-(%sp)
	move.l 44+4(%sp),%a5
	move.l 44+8(%sp),%a6
	move.l 44+16(%sp),%a0
	move.l 44+12(%sp),%d0
	move.l %sp,saved_csp
	lea (%a5,%d0.l),%sp
	moveq #0,%d0
	moveq #0,%d1
	moveq #0,%d2
	moveq #0,%d3
	moveq #0,%d4
	move.l #0x170,%d5
	moveq #0,%d6
	jsr (%a0)
	move.l saved_csp,%sp
	movem.l (%sp)+,%d2-%d7/%a2-%a6
	rts
	.globl rt_leave
rt_leave:
	move.l saved_csp,%sp
	movem.l (%sp)+,%d2-%d7/%a2-%a6
	rts
	.bss
	.align 4
saved_csp: .space 4
rt_cstack: .space 32768
	.globl rt_cstack_top
rt_cstack_top:
	.text

| common exit: return to the translated caller, erasing the return address from the x86 stack
.macro RET_CLEAN
	move.l (%sp)+,%a0
	clr.l -4(%sp)
	jmp (%a0)
.endm
''')
# ---- INT stubs
for v in range(256):
    h = '%02x' % v
    w(f'''
	.globl rt_int_{h}
rt_int_{h}:
	movem.l %d0-%d6,{CTXREGS}(%a6)
	move.l %sp,%a4
	lea rt_cstack_top,%sp
	pea {CTXREGS}(%a6)
	pea 0x{h}.w
	jbsr rt_c_int
	move.l %d0,%d7
	move.l %a4,%sp
	movem.l {CTXREGS}(%a6),%d0-%d6
	move.l (%sp)+,%a0
	clr.l -4(%sp)
	lsr.l #1,%d7			| C = carry returned by the service
	jmp (%a0)
''')
# ---- in/out
for sz, name in ((1, 8), (2, 16), (4, 32)):
    w(f'''
	.globl rt_in{name}
rt_in{name}:				| a0 = port; result in d7
	movem.l %d0-%d1,{CTXREGS}(%a6)
	move.l %sp,%a4
	lea rt_cstack_top,%sp
	pea {sz}.w
	move.l %a0,%d0
	and.l #0xffff,%d0
	move.l %d0,-(%sp)
	jbsr rt_c_in
	move.l %d0,%d7
	move.l %a4,%sp
	movem.l {CTXREGS}(%a6),%d0-%d1
	RET_CLEAN

	.globl rt_out{name}
rt_out{name}:				| a0 = port, d7 = value
	movem.l %d0-%d1,{CTXREGS}(%a6)
	move.l %sp,%a4
	lea rt_cstack_top,%sp
	pea {sz}.w
	move.l %d7,-(%sp)
	move.l %a0,%d0
	and.l #0xffff,%d0
	move.l %d0,-(%sp)
	jbsr rt_c_out
	move.l %a4,%sp
	movem.l {CTXREGS}(%a6),%d0-%d1
	RET_CLEAN
''')
# ---- string ops
ops = []
for pfx in ('', 'rep_', 'repe_', 'repne_'):
    for kind in ('movs', 'stos', 'lods', 'scas', 'cmps', 'outs'):
        for sz in 'bwd':
            ops.append(f'{pfx}{kind}{sz}')
for idx, nm in enumerate(ops):
    flagop = 'scas' in nm or 'cmps' in nm
    w(f'''
	.globl rt_{nm}
rt_{nm}:
	move.w %ccr,{CTXREGS + 40}(%a6)
	movem.l %d0-%d6,{CTXREGS}(%a6)
	move.l %sp,%a4
	lea rt_cstack_top,%sp
	pea {CTXREGS}(%a6)
	pea {idx}.w
	jbsr rt_c_str
	move.l %d0,%d7
	move.l %a4,%sp
	movem.l {CTXREGS}(%a6),%d0-%d6
	move.l (%sp)+,%a0
	clr.l -4(%sp)
''' + ('	move.w %d7,%ccr\n' if flagop else f'	move.w {CTXREGS + 40}(%a6),%ccr\n') + '	jmp (%a0)\n')
# ---- poll (loop heads): may deliver interrupts
w(f'''
	.globl rt_poll, rt_dbg_pc
	.data
rt_dbg_pc:	.long 0
	.text
rt_poll:
	move.w %ccr,{CTXREGS + 40}(%a6)
	movem.l %d0-%d6,{CTXREGS}(%a6)
1:	move.l (%sp),rt_dbg_pc
	move.l %sp,%a4
	lea rt_cstack_top,%sp
	pea {CTXREGS}(%a6)
	jbsr rt_c_poll
	move.l %a4,%sp
	tst.l %d0
	beq 2f
	move.l %d0,%a1
	movem.l {CTXREGS}(%a6),%d0-%d6
	clr.b 4(%a6)			| interrupts are off inside the handler until its iretd restores IF
	move.l 32(%a6),-(%sp)		| eflags image of the interrupted code (built by C), cs and the sentinel return address
	pea 0x78010000
	pea XL_SENT_BE
	jmp (%a1)
	.globl rt_isr_return
rt_isr_return:
	move.w %ccr,{CTXREGS + 40}(%a6)	| iretd restored the interrupted flags
	movem.l %d0-%d6,{CTXREGS}(%a6)
	bra 1b
2:	movem.l {CTXREGS}(%a6),%d0-%d6
	move.w {CTXREGS + 40}(%a6),%ccr
	RET_CLEAN

	.globl rt_dispatch_miss
rt_dispatch_miss:
	move.l (%sp),%a0
	move.l %d7,%d0
	lea rt_cstack_top,%sp
	move.l %a0,-(%sp)
	move.l %d0,-(%sp)
	jbsr rt_c_badtarget
	rts
	.globl rt_unimpl
	.globl rt_badjump
rt_unimpl:
rt_badjump:
	move.l (%sp),%a0
	move.l (%a0),%d0
	lea rt_cstack_top,%sp
	move.l %d0,-(%sp)
	jbsr rt_c_unimpl
	rts

	.globl rt_int3
rt_int3:
	RET_CLEAN

	.globl rt_pushfd
rt_pushfd:
	move.w %ccr,%d7
	move.w %d7,{CTXREGS + 40}(%a6)
	movem.l %d0-%d1,{CTXREGS}(%a6)
	and.l #0xff,%d7
	move.l %sp,%a4
	lea rt_cstack_top,%sp
	move.l %d7,-(%sp)
	jbsr rt_mk_eflags
	move.l %d0,%d7
	move.l %a4,%sp
	movem.l {CTXREGS}(%a6),%d0-%d1
	ror.w #8,%d7
	swap %d7
	ror.w #8,%d7
	move.l (%sp)+,%a0
	move.l %d7,-(%sp)		| the pushed eflags replaces the return address slot
	move.w {CTXREGS + 40}(%a6),%ccr
	jmp (%a0)

	.globl rt_popfd
rt_popfd:
	move.l (%sp)+,%a1
	move.l (%sp)+,%d7
	clr.l -4(%sp)
	clr.l -8(%sp)
	ror.w #8,%d7
	swap %d7
	ror.w #8,%d7
	movem.l %d0-%d1,{CTXREGS}(%a6)
	move.l %sp,%a4
	lea rt_cstack_top,%sp
	move.l %d7,-(%sp)
	jbsr rt_set_eflags
	move.l %d0,%d7
	move.l %a4,%sp
	movem.l {CTXREGS}(%a6),%d0-%d1
	move.w %d7,%ccr
	jmp (%a1)
''')
for nm, which in (('es', 0), ('fs', 1), ('gs', 2), ('ds', 3), ('ss', 4), ('cs', 5)):
    w(f'''
	.globl rt_setseg_{nm}
rt_setseg_{nm}:
	movem.l %d0-%d1,{CTXREGS}(%a6)
	and.l #0xffff,%d7
	move.l %sp,%a4
	lea rt_cstack_top,%sp
	move.l %d7,-(%sp)
	pea {which}.w
	jbsr rt_c_setseg
	move.l %a4,%sp
	movem.l {CTXREGS}(%a6),%d0-%d1
	RET_CLEAN
''')
w(f'''
	.globl rt_vga_rd8
rt_vga_rd8:				| d7 = x86 linear address; returns byte in d7 (VGA window aware)
	move.l %d7,%a0
	cmp.l #0xA0000,%d7
	bcs.s 1f
	cmp.l #0xB0000,%d7
	bcc.s 1f
	movem.l %d0-%d1,{CTXREGS}(%a6)
	move.l %sp,%a4
	lea rt_cstack_top,%sp
	pea 1.w
	move.l %d7,-(%sp)
	jbsr vga_read
	move.l %d0,%d7
	move.l %a4,%sp
	movem.l {CTXREGS}(%a6),%d0-%d1
	RET_CLEAN
1:	moveq #0,%d7
	move.b (%a5,%a0.l),%d7
	RET_CLEAN

	.globl rt_iretd
rt_iretd:				| stack: [eip][cs][eflags] (all LE); restores CF/ZF/SF/OF and IF from the image
	move.l (%sp)+,%d7
	clr.l -4(%sp)
	ror.w #8,%d7
	swap %d7
	ror.w #8,%d7
	sub.l #XL_BASE,%d7
	lea (xl_tab,%pc),%a0
	move.l (%a0,%d7.l*4),%a1
	addq.l #4,%sp
	moveq #0,%d7
	btst #0,(%sp)
	beq 1f
	ori.b #1,%d7
1:	btst #6,(%sp)
	beq 2f
	ori.b #4,%d7
2:	btst #7,(%sp)
	beq 3f
	ori.b #8,%d7
3:	btst #3,1(%sp)
	beq 4f
	ori.b #2,%d7
4:	btst #1,1(%sp)
	sne 4(%a6)
	addq.l #4,%sp
	clr.l -4(%sp)
	move.w %d7,%ccr
	jmp (%a1)

	.ifdef HOSTED
	.globl rt_trace
rt_trace:				| debug/replay build: log eip, optionally inject a recorded interrupt before the instruction
	move.w %ccr,{CTXREGS + 40}(%a6)
	movem.l %d0-%d6,{CTXREGS}(%a6)
	move.l (%sp)+,%a2		| return address (points at the .long)
	clr.l -4(%sp)
1:	move.l %sp,%a4
	lea rt_cstack_top,%sp
	pea {CTXREGS}(%a6)
	move.l (%a2),-(%sp)
	jbsr rt_c_trace
	move.l %a4,%sp
	tst.l %d0
	beq 2f
	move.l %d0,%a1
	movem.l {CTXREGS}(%a6),%d0-%d6
	clr.b 4(%a6)
	move.l %a2,-(%sp)
	move.l 32(%a6),-(%sp)
	pea 0x78010000
	pea XL_SENT_BE_TRACE
	jmp (%a1)
	.globl rt_trace_isr_return
rt_trace_isr_return:
	move.w %ccr,{CTXREGS + 40}(%a6)
	move.l (%sp)+,%a2
	clr.l -4(%sp)
	movem.l %d0-%d6,{CTXREGS}(%a6)
	bra 1b
2:	movem.l {CTXREGS}(%a6),%d0-%d6
	move.w {CTXREGS + 40}(%a6),%ccr
	jmp 4(%a2)
	.endif
''')
open(__import__('os').path.join(__import__('os').path.dirname(__import__('os').path.abspath(__file__)), 'rt_asm.s'), 'w').write(''.join(OUT))
