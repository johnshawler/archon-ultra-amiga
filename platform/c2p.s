| c2p_row320(src, dst): 320 chunky bytes (4-byte aligned) -> one screen line: plane p at dst + 40*p
c2p_row320:
	movem.l %d2-%d4/%d7/%a3,-(%sp)
	move.l 24(%sp),%a0
	move.l 28(%sp),%a1
	moveq #19,%d7
1:	jbsr .Lpair
	lea 16(%a0),%a0
	addq.l #2,%a1
	dbra %d7,1b
	movem.l (%sp)+,%d2-%d4/%d7/%a3
	rts
| c2p_row320_dirty(src, dst, flags, mask): per 16-pixel group, convert only if (flags[k] & mask); clears the mask bits it consumed
c2p_row320_dirty:
	movem.l %d2-%d7/%a2-%a3,-(%sp)
	move.l 36(%sp),%a0
	move.l 40(%sp),%a1
	move.l 44(%sp),%a2
	move.l 48(%sp),%d5
	move.l %d5,%d6
	not.b %d6
	moveq #19,%d7
1:	move.b (%a2),%d4
	and.b %d5,%d4
	jbeq 2f
	and.b %d6,(%a2)
	jbsr .Lpair
2:	lea 16(%a0),%a0
	addq.l #2,%a1
	addq.l #1,%a2
	dbra %d7,1b
	movem.l (%sp)+,%d2-%d7/%a2-%a3
	rts
	.section .rodata
	.even
