	eor.l %d3,%d4
	and.l #0x33333333,%d4
	eor.l %d4,%d3
	lsl.l #2,%d4
	eor.l %d4,%d2
	move.l %d0,%d4
	lsr.l #1,%d4
	eor.l %d2,%d4
	and.l #0x55555555,%d4
	eor.l %d4,%d2
	lsl.l #1,%d4
	eor.l %d4,%d0
